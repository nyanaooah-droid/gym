# ---- animation ------------------------------------------------------------
def lerp(a, b, t):
    if isinstance(a, (int, float)): return a + (b - a) * t
    return type(a)(lerp(x, y, t) for x, y in zip(a, b)) if not isinstance(a, list) else [lerp(x, y, t) for x, y in zip(a, b)]

def end_pose(p):
    return {k: p['to'].get(k, p[k]) for k in ('s', 'h', 'a', 'l')}

def at(p, t):
    e = end_pose(p)
    return {k: lerp(p[k], e[k], t) for k in ('s', 'h', 'a', 'l')}

def draw_frame(p, t):
    j = at(p, t)
    img = Image.new('RGB', (W*SS, H*SS), BG)
    d = ImageDraw.Draw(img)
    S = lambda v: v * SS
    def line(x1, y1, x2, y2, col, w):
        d.line([S(x1), S(y1), S(x2), S(y2)], fill=col, width=int(w*SS))
        for x, y in ((x1, y1), (x2, y2)):
            d.ellipse([S(x)-w*SS/2, S(y)-w*SS/2, S(x)+w*SS/2, S(y)+w*SS/2], fill=col)
    def circ(x, y, r, col, w):
        d.ellipse([S(x-r), S(y-r), S(x+r), S(y+r)], outline=col, width=int(w*SS))
    def poly(pts, col, w):
        for a, b in zip(pts, pts[1:]): line(*a, *b, col, w)

    line(6, 72, 114, 72, FLOOR, 2.2)
    for it in p['st']:
        if it[0] == 'l': line(*it[1:], PROP, 2.2)
        elif it[0] == 'c': circ(it[1], it[2], it[3], PROP, 2.2)
        elif it[0] == 'p': poly(list(it[1]), PROP, 2.2)
    hand = lambda i: j['a'][i][1]
    for m in p['mv']:
        k = m[0]
        if k in ('bell', 'db', 'ring', 'wheel'):
            x, y = hand(m[1]); dx, dy = (m[2], m[3]) if len(m) > 3 else (0, 0)
            r = {'bell': 6, 'db': 3.5, 'ring': 3.5, 'wheel': 6}[k]
            if k == 'bell' and len(m) > 4: r = m[4]
            circ(x+dx, y+dy, r, PROP, 2.2)
        elif k == 'bellAt':
            x, y = j[m[1]]; circ(x+m[2], y+m[3], 6, PROP, 2.2)
        elif k == 'cable':
            ax, ay = m[1]; x, y = hand(m[2]); circ(ax, ay, 2, PROP, 2); line(ax, ay, x, y, PROP, 2.2)
        elif k == 'hbar':
            x, y = hand(m[1]); line(x-m[2], y, x+m[2], y, PROP, 2.2)
        elif k == 'bar2':
            (x1, y1), (x2, y2) = hand(m[1]), hand(m[2])
            line(x1-6, y1, x2+6, y2, PROP, 2.2); circ(x1-6, y1, 6, PROP, 2.2); circ(x2+6, y2, 6, PROP, 2.2)
        elif k == 'footplate':
            x, y = j['l'][m[1]][1]; line(x-4, y-8, x+4, y+8, PROP, 2.2)
    sx, sy = j['s']; hx, hy = j['h']
    n = math.hypot(sx-hx, sy-hy) or 1
    hd = (sx + (sx-hx)/n*9, sy + (sy-hy)/n*9)
    circ(*hd, 5, BODY, 3)
    line(sx, sy, hx, hy, BODY, 3)
    for e, h in j['a']: poly([j['s'], e, h], BODY, 3)
    for k, f in j['l']: poly([j['h'], k, f], BODY, 3)
    return img.resize(OUT, Image.LANCZOS)

def ease(t): return 0.5 - 0.5 * math.cos(math.pi * t)

def make(key, outdir):
    p = P[key]; N = 10
    frames, durs = [], []
    for i in range(N + 1):
        frames.append(draw_frame(p, ease(i / N))); durs.append(500 if i == N else 60)
    for i in range(N - 1, 0, -1):
        frames.append(draw_frame(p, ease(i / N))); durs.append(60)
    frames[0].info = {}
    durs[0] = 400
    q = [f.quantize(colors=16, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE) for f in frames]
    q[0].save(os.path.join(outdir, key + '.gif'), save_all=True, append_images=q[1:], duration=durs, loop=0, optimize=True, disposal=1)

if __name__ == '__main__':
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'gifs')
    os.makedirs(out, exist_ok=True)
    for k in P: make(k, out)
    print(len(P), 'gifs written to', os.path.normpath(out))
